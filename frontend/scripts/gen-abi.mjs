// Regenerates lib/abi from the Foundry build and refreshes lib/deployment.json. Run `forge build` first.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";

const names = ["KancyVault", "ManagerRegistry", "VaultFactory", "EpochSettler", "PositionBook", "OracleAdapter", "MockToken"];
let out = "// Generated by scripts/gen-abi.mjs. Do not edit.\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(new URL(`../../contracts/out/${n}.sol/${n}.json`, import.meta.url), "utf8"));
  // events are indexed by Ponder; the app only needs calls and custom errors
  const slim = abi.filter((x) => x.type === "function" || x.type === "error");
  out += `\nexport const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(slim)} as const;\n`;
}
writeFileSync(new URL("../lib/abi/index.ts", import.meta.url), out);
copyFileSync(new URL("../../contracts/deployments/unichain-sepolia.json", import.meta.url), new URL("../lib/deployment.json", import.meta.url));
console.log("abi + deployment written");
